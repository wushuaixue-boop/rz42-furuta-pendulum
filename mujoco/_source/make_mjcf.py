"""Build the MJCF for the assembled RZ42 v5 (608ZZ) rotary inverted pendulum.

Masses/inertias come from massprops.json (exact B-rep volumes/areas, 15% infill +
solid shells, coin, magnet, bearing, hardware). Friction of the pendulum joint uses
the repo's measured 608 values (policy/sysid_params_rig2.json). Units: SI.
"""
import json, math, sys
from pathlib import Path

out = Path(sys.argv[1] if len(sys.argv) > 1 else "mjx")
mp = json.load(open(out / "massprops.json"))
G2KG, MM = 1e-3, 1e-3

def inertial(b):
    m = b["mass_g"] * G2KG
    c = [v * MM for v in b["com_mm"]]
    I = [v * G2KG * MM * MM for v in b["I_gmm2"]]   # g*mm^2 -> kg*m^2, tensor (ixx iyy izz ixy ixz iyz)
    return m, c, I

ma, ca, Ia = inertial(mp["arm"])
mpd, cp, Ip = inertial(mp["pendulum"])

# pendulum joint friction: measured free-swing fit of a 608 rig in this repo (rig2)
PEN_VISC = 1.7437187042217898e-05      # N*m*s
PEN_COUL = 3.457163562668972e-05       # N*m
ROTOR_J = 6.8e-6                        # kg*m^2, typical 42x48 stepper rotor (68 g*cm^2)
ARM_DAMP = 1e-4                         # N*m*s, bearing drag of the motor (small)
KP = 1000.0                             # stiff position servo: the closed-loop stepper follows its command
# effective inertia seen by the motor at pendulum hanging (for critical damping of the servo)
r_p = mp["piv_x_mm"] * MM
I_motor = Ia[2] + ma * (ca[0] ** 2 + ca[1] ** 2) + ROTOR_J + mpd * (r_p ** 2) + Ip[1]
KV = 2 * math.sqrt(KP * I_motor)
TORQUE_MAX = 0.45                      # N*m, 42x48 stepper usable torque (holding ~0.55)

f = lambda v: " ".join(f"{x:.9g}" for x in v)
xml = f"""<mujoco model="RZ42_v5_rotary_inverted_pendulum">
  <!-- Generated by make_mjcf.py from the RZ42 v5 CAD (608ZZ). Units: m, kg, s.
       Printed parts: PLA 1.24 g/cm3, {mp['infill']*100:.0f}% infill, {mp['shell_mm']} mm solid shells.
       Arm body {ma*1e3:.2f} g, pendulum body {mpd*1e3:.2f} g (incl. 7.12 g coin). -->
  <compiler angle="radian" meshdir="meshes"/>
  <option timestep="0.001" integrator="implicitfast" gravity="0 0 -9.81"/>
  <visual>
    <global offwidth="1280" offheight="720" azimuth="135" elevation="-20"/>
    <quality shadowsize="4096"/>
  </visual>
  <default>
    <geom contype="0" conaffinity="0" group="1"/>
    <mesh scale="0.001 0.001 0.001"/>
  </default>
  <asset>
    <texture name="grid" type="2d" builtin="checker" rgb1="0.92 0.92 0.92" rgb2="0.85 0.85 0.85" width="512" height="512"/>
    <material name="floor" texture="grid" texrepeat="8 8"/>
    <material name="enclosure" rgba="0.25 0.25 0.28 1"/>
    <material name="lid" rgba="0.42 0.42 0.48 1"/>
    <material name="metal" rgba="0.75 0.75 0.78 1"/>
    <material name="pcb" rgba="0.10 0.50 0.25 1"/>
    <material name="battery" rgba="0.20 0.35 0.80 1"/>
    <material name="arm" rgba="0.40 0.60 0.80 1"/>
    <material name="housing" rgba="0.95 0.60 0.20 1"/>
    <material name="pendulum" rgba="0.80 0.30 0.30 1"/>
    <mesh name="base" file="base.stl"/>
    <mesh name="lid" file="lid.stl"/>
    <mesh name="motor" file="motor.stl"/>
    <mesh name="driver" file="driver.stl"/>
    <mesh name="battery" file="battery.stl"/>
    <mesh name="arm" file="arm.stl"/>
    <mesh name="housing" file="housing.stl"/>
    <mesh name="bearing" file="bearing.stl"/>
    <mesh name="as5600" file="as5600.stl"/>
    <mesh name="pendulum" file="pendulum.stl"/>
    <mesh name="magnet" file="magnet.stl"/>
  </asset>
  <worldbody>
    <light pos="0.3 -0.3 0.8" dir="-0.3 0.3 -0.8" diffuse="0.8 0.8 0.8" castshadow="true"/>
    <light pos="-0.3 0.3 0.6" dir="0.3 -0.3 -0.6" diffuse="0.3 0.3 0.3" castshadow="false"/>
    <geom name="floor" type="plane" size="0.5 0.5 0.01" material="floor"/>
    <camera name="side" pos="0.28 -0.36 0.22" xyaxes="0.79 0.61 0 -0.22 0.29 0.93"/>
    <!-- fixed parts (welded to the world) -->
    <geom name="base" type="mesh" mesh="base" material="enclosure"/>
    <geom name="lid" type="mesh" mesh="lid" material="lid"/>
    <geom name="motor" type="mesh" mesh="motor" material="metal"/>
    <geom name="driver" type="mesh" mesh="driver" material="pcb"/>
    <geom name="battery" type="mesh" mesh="battery" material="battery"/>
    <!-- arm: URDF zero = arm pointing along -y -->
    <body name="arm" pos="0 0 {mp['arm_z_mm']*MM:.6g}" euler="0 0 {-math.pi/2:.9g}">
      <joint name="arm_joint" type="hinge" axis="0 0 1" range="-2.35619449 2.35619449" limited="true"
             armature="{ROTOR_J}" damping="{ARM_DAMP}"/>
      <inertial pos="{f(ca)}" mass="{ma:.9g}" fullinertia="{f(Ia)}"/>
      <geom name="arm" type="mesh" mesh="arm" material="arm"/>
      <geom name="housing" type="mesh" mesh="housing" material="housing"/>
      <geom name="bearing" type="mesh" mesh="bearing" material="metal"/>
      <geom name="as5600" type="mesh" mesh="as5600" material="pcb"/>
      <site name="arm_tip" pos="0.058 0 0.014" size="0.002"/>
      <!-- pendulum: hinge along the arm (x), at the 608 centre line -->
      <body name="pendulum" pos="{mp['piv_x_mm']*MM:.6g} 0 {mp['piv_z_mm']*MM:.6g}">
        <joint name="pendulum_joint" type="hinge" axis="1 0 0" damping="{PEN_VISC:.9g}" frictionloss="{PEN_COUL:.9g}"/>
        <inertial pos="{f(cp)}" mass="{mpd:.9g}" fullinertia="{f(Ip)}"/>
        <geom name="pendulum" type="mesh" mesh="pendulum" material="pendulum"/>
        <geom name="magnet" type="mesh" mesh="magnet" material="metal"/>
        <site name="pendulum_tip" pos="0 0 -0.08" size="0.003" rgba="1 1 0 1"/>
      </body>
    </body>
  </worldbody>
  <actuator>
    <!-- closed-loop stepper modelled as a stiff, torque-limited position servo -->
    <position name="motor" joint="arm_joint" kp="{KP}" kv="{KV:.6g}" ctrlrange="-2.18 2.18"
              forcerange="-{TORQUE_MAX} {TORQUE_MAX}" forcelimited="true"/>
  </actuator>
  <sensor>
    <jointpos name="arm_angle" joint="arm_joint"/>
    <jointpos name="pendulum_angle" joint="pendulum_joint"/>
    <jointvel name="arm_vel" joint="arm_joint"/>
    <jointvel name="pendulum_vel" joint="pendulum_joint"/>
    <actuatorfrc name="motor_torque" actuator="motor"/>
  </sensor>
</mujoco>
"""
(out / "rz42_pendulum.xml").write_text(xml)
print(f"arm {ma*1e3:.2f} g, pendulum {mpd*1e3:.2f} g, motor-side inertia {I_motor:.3e} kg m2, kv {KV:.4f}")
# small-angle natural frequency of the pendulum about its pivot
d = math.hypot(cp[1], cp[2]); Ipiv = Ip[0] + mpd * (cp[1] ** 2 + cp[2] ** 2)
wn = math.sqrt(mpd * 9.81 * d / Ipiv)
print(f"pendulum: COM {d*1e3:.2f} mm below pivot, I_pivot {Ipiv:.4e} kg m2, wn {wn:.3f} rad/s = {wn/2/math.pi:.3f} Hz")
json.dump({"wn": wn, "fn": wn / 2 / math.pi, "I_pivot": Ipiv, "d": d, "m_pen": mpd, "m_arm": ma, "I_motor": I_motor},
          open(out / "derived.json", "w"), indent=1)
